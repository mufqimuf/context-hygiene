#!/usr/bin/env python3
"""
install.py — Interactive installer for context-hygiene.

Walks the user through setup and writes a working cron line:

  1. Detect installed AI tools (hermes / claude-code / codex / opencode).
  2. Choose MODE:
       notify  → every run, warnings are SENT to you (Telegram / chat session
                 / webhook). You type /new yourself.  ← recommended
       auto    → sessions are reset directly (idle-guarded, archived, no ask).
  3. If notify + telegram: ask chat id, verify TELEGRAM_BOT_TOKEN is set.
  4. Write the crontab entry (and a wrapper script in ~/.context-hygiene/).

Re-run any time to change settings — it replaces its own previous entry.
"""

from __future__ import annotations

import os
import subprocess
import sys
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
INSTALL_DIR = Path.home() / ".context-hygiene"
MARKER = "# context-hygiene"


def detect_tools() -> list[str]:
    found = []
    checks = {
        "hermes": Path.home() / ".hermes" / "state.db",
        "claude-code": Path.home() / ".claude" / "projects",
        "codex": Path.home() / ".codex" / "sessions",
        "opencode": Path.home() / ".local" / "share" / "opencode" / "storage",
    }
    for name, p in checks.items():
        if p.exists():
            found.append(name)
    return found


def ask(prompt: str, default: str = "") -> str:
    suffix = f" [{default}]" if default else ""
    val = input(f"{prompt}{suffix}: ").strip()
    return val or default


def pick_tools(found: list[str]) -> str:
    if not found:
        print("Tidak ada tool AI terdeteksi — pakai --extra-dir manual nanti.")
        return ""
    print("\nTool AI terdeteksi:")
    for i, t in enumerate(found, 1):
        print(f"  {i}. {t}")
    sel = ask("Pakai yang mana? (nomor, comma untuk banyak, Enter=semua)", "")
    if not sel:
        return ",".join(found)
    picks = []
    for s in sel.split(","):
        try:
            picks.append(found[int(s.strip()) - 1])
        except (ValueError, IndexError):
            print(f"  skip pilihan tak dikenal: {s}")
    return ",".join(picks) if picks else ",".join(found)


def pick_mode() -> str:
    print("\nMODE reset:")
    print("  1. notify (RECOMMENDED) — bot ngasih tahu kamu, kamu ketik /new sendiri")
    print("  2. auto — reset langsung tanpa tanya (idle-guard, diarsipkan, gak ada yang dihapus)")
    while True:
        c = ask("Pilih (1/2)", "1")
        if c in ("1", "2"):
            return "notify" if c == "1" else "auto"


def pick_notify_target() -> str:
    print("\nKirim pemberitahuannya ke mana?")
    print("  1. Chat/session yang lagi dipakai (stdout — cocok buat cron Hermes deliver origin)")
    print("  2. Telegram (butuh TELEGRAM_BOT_TOKEN di environment)")
    print("  3. Webhook URL (ntfy / Slack / Discord)")
    while True:
        c = ask("Pilih (1/2/3)", "2")
        if c == "1":
            return "session"
        if c == "2":
            chat = ask("Chat ID Telegram kamu")
            token = os.environ.get("TELEGRAM_BOT_TOKEN", "")
            if not token:
                tok = ask("TELEGRAM_BOT_TOKEN belum ada di env. Paste token sekarang (kosong=skip verifikasi)")
                if tok:
                    token = tok
            if token:
                ok = _test_telegram(token, chat)
                if not ok and not ask("Tes gagal, tetap lanjut? (y/N)").lower().startswith("y"):
                    continue
            return f"telegram:{chat}"
        if c == "3":
            return ask("Webhook URL")
        print("  masukin 1, 2, atau 3")


def _test_telegram(token: str, chat: str) -> bool:
    body = f"chat_id={chat}&text=context-hygiene: tes notifikasi ✓".encode()
    req = urllib.request.Request(
        f"https://api.telegram.org/bot{token}/sendMessage", data=body)
    try:
        with urllib.request.urlopen(req, timeout=15) as r:
            print("✓ tes notifikasi terkirim!")
            return r.status == 200
    except Exception as e:
        print(f"✗ gagal: {e}")
        return False


def write_wrapper(tools: str, mode: str, notify: str,
                  max_age: int, max_tokens: int) -> Path:
    INSTALL_DIR.mkdir(exist_ok=True)
    script = INSTALL_DIR / "run_check.sh"
    notify_flag = ""
    if mode == "notify":
        notify_flag = f" --notify {notify!r}" if notify != "session" else ""
    script.write_text(f"""#!/bin/bash
# context-hygiene runner (generated by install.py — safe to re-run installer)
cd {HERE}
OUT=$(python3 context_hygiene.py --tools {tools} \\
      --max-age-hours {max_age} --max-prompt-tokens {max_tokens} --json) || true
echo "$OUT" | python3 reset_modes.py --mode {mode}{notify_flag} \\
    --warnings-file -
""", )
    script.chmod(0o755)
    return script


def write_crontab(script: Path, schedule: str) -> bool:
    cron_line = f"{schedule} {script} {MARKER}"
    cur = subprocess.run(["crontab", "-l"], capture_output=True, text=True)
    lines = [l for l in (cur.stdout or "").splitlines() if MARKER not in l]
    lines.append(cron_line)
    new = "\n".join(lines) + "\n"
    r = subprocess.run(["crontab", "-"], input=new, capture_output=True, text=True)
    return r.returncode == 0


def main() -> int:
    print("=" * 50)
    print(" context-hygiene installer")
    print("=" * 50)
    found = detect_tools()
    tools = pick_tools(found)
    mode = pick_mode()
    notify = "session"
    if mode == "notify":
        notify = pick_notify_target()
    else:
        print("\n⚠ mode auto: reset terjadi TANPA pemberitahuan (idle-guard tetap aktif).")
    max_age = int(ask("Max umur sesi (jam)", "48"))
    max_tokens = int(ask("Max prompt tokens", "60000"))
    schedule = ask("Jadwal cron (format crontab)", "0 9 * * *")

    script = write_wrapper(tools, mode, notify, max_age, max_tokens)
    ok = write_crontab(script, schedule)
    print()
    if ok:
        print(f"✓ Terpasang! Wrapper: {script}")
        print(f"  Cron: {schedule} → jalankan check ({mode} mode)")
        if mode == "notify":
            print(f"  Notifikasi → {notify}")
        print("\nUji manual sekarang:")
        print(f"  bash {script}")
    else:
        print(f"✗ crontab gagal. Jalankan manual: {script}")
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
